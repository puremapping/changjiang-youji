def _row(canonical, variants, modern, lat, lon, ptype, note):
    # 规范名即 id 主体；若 canonical 本身已带「pl-」前缀（如占位 alias 条目），直接用
    pid = canonical if canonical.startswith('pl-') else 'pl-' + canonical
    return {
        'id': pid,
        'name': canonical,
        'name_variants': variants,
        'modern_name': modern,
        'lat': lat,
        'lon': lon,
        'place_type': ptype,
        'note': note,
    }


def build():
    out = []
    seen_canon = set()
    for p in PLACES:
        canonical, variants, modern, lat, lon, ptype, note = p
        if canonical in seen_canon:
            continue
        seen_canon.add(canonical)
        out.append(_row(canonical, variants, modern, lat, lon, ptype, note))
    return out


